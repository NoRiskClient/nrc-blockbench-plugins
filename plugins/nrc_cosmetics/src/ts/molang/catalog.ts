export type Support = 'yes' | 'partial' | 'no';
export type MolangContext = 'cosmetic' | 'emote' | 'particle';
export type MolangKind = 'query' | 'variable' | 'function' | 'syntax';
export type DemoBone = 'head' | 'body' | 'right_arm' | 'left_arm' | 'right_leg' | 'left_leg';
export type DemoChannel = 'rotation' | 'position';
export type DemoAxis = 'x' | 'y' | 'z';

export interface MolangDemo {
    caption: string;
    expression?: string;
    bone?: DemoBone;
    channel?: DemoChannel;
    axis?: DemoAxis;
    seconds?: number;
    loop?: number;
    sim?: 'walk' | 'sneak' | `pose:${DemoBone}`;
    particle?: boolean;
    compare?: string[];
}

export interface MolangEntry {
    name: string;
    aliases: string[];
    kind: MolangKind;
    contexts: MolangContext[];
    summary: string;
    returns: string;
    updates: string;
    example?: string;
    support: { client: Support; web: Support; blockbench: Support };
    caveat?: string;
    placeholder?: string;
    source: string;
    usage?: number;
    usedIn?: string[];
    demo?: MolangDemo;
}

